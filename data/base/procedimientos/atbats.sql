      -- Trajectories
      SUM(IF( trajectory = 'fly_ball', 1, 0 ) ) AS flyBalls,
      SUM(IF( trajectory = 'ground_ball', 1, 0 ) ) AS groundBalls,
      SUM(IF( trajectory = 'line_drive', 1, 0 ) ) AS lineDrives,
      SUM(IF( trajectory = 'popup', 1, 0 ) ) AS popUps,
