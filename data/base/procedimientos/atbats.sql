      SUM(IF( trajectory = 'bunt_grounder' AND heatMapEight = 'RF1', 1, 0 )) AS heatMapEightRightFieldOneGroundBunts,
      SUM(IF( trajectory = 'bunt_popup' AND heatMapEight = 'RF1', 1, 0 )) AS heatMapEightRightFieldOnePopUpBunts,
      SUM(IF( trajectory = 'bunt_line_drive' AND heatMapEight = 'RF1', 1, 0 )) AS heatMapEightRightFieldOneLineDriveBunts,
      SUM(IF( trajectory = 'fly_ball' AND heatMapEight = 'RF2', 1, 0 )) AS heatMapEightRightFieldTwoFlyBalls,
